    struct { const char* label; double hz; int amp; bool pocket; int truth; } cases[] = {
        { "walk 2.0Hz 350mg upright", 2.0, 350, false, 40 },
        { "walk 1.2Hz 260mg upright", 1.2, 260, false, 24 },
        { "walk 2.6Hz 420mg upright", 2.6, 420, false, 52 },
        { "walk 2.0Hz 240mg pocket",  2.0, 240, true,  40 },
        { "walk 1.2Hz 180mg pocket",  1.2, 180, true,  24 },
    };
    for (auto& c : cases) {
        StepDetector d;
        d.reset();
        int n = (int)(20000 / DT);
        for (int i = 0; i < n; i++) {
            Sample s = c.pocket ? pocketSample(i, DT, c.hz, c.amp)
                                : walkSample(i, DT, c.hz, c.amp);
            d.update((uint32_t)(i * DT), s.ax, s.ay, s.az);
        }
        printf("  %-26s truth %3d  counted %3lu  (%+d)\n",
               c.label, c.truth, (unsigned long)d.steps(),
               (int)d.steps() - c.truth);
    }

    printf("\n=== %d passed, %d failed ===\n\n", s_testsPassed, s_testsFailed);
    return s_testsFailed > 0 ? 1 : 0;
