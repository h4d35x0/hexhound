// ── Runner ────────────────────────────────────────────────────────────────

// ── A real counted walk ───────────────────────────────────────────────────
//
// Everything above this point is synthetic, and synthetic input turned out to be
// incapable of discriminating between tuning constants at all: a clean spike
// clears every threshold, so every candidate parameter set scores identically.
// Only a real pocket, with a real noise floor, tells you anything. This fixture
// is one such walk, 118-119 steps counted by hand.
//
// It is split in two on purpose. A TOTAL is not a measure of correctness here:
// the walk that produced this fixture undercounted the walking phase by 5 and
// then invented 6 steps while the walker sat down, so the total landed on 119
// against 118-119 counted and looked perfect. Scoring on the total would have
// called that a success.
static void replayCapture(int samples, const unsigned short* dt,
                          const short* ax, const short* ay, const short* az,
                          uint32_t walkEndMs,
                          uint32_t* outWalk, uint32_t* outAfter) {
    StepDetector d;
    d.reset();
    uint32_t t = 0, walk = 0, after = 0;
    for (int i = 0; i < samples; i++) {
        t += dt[i];
        const uint8_t committed = d.update(t, ax[i], ay[i], az[i]);
        if (t <= walkEndMs) walk += committed;
        else                after += committed;
    }
    *outWalk = walk;
    *outAfter = after;
}

static void replayFixture(uint32_t* outWalk, uint32_t* outSeated) {
    replayCapture(WALK_FIXTURE_SAMPLES, kWalkDt, kWalkAx, kWalkAy, kWalkAz,
                  WALK_FIXTURE_WALK_END_MS, outWalk, outSeated);
}

static void replayFixture2(uint32_t* outWalk, uint32_t* outStill) {
    replayCapture(WALK2_FIXTURE_SAMPLES, kWalk2Dt, kWalk2Ax, kWalk2Ay, kWalk2Az,
                  WALK2_FIXTURE_WALK_END_MS, outWalk, outStill);
}

static void test_real_walk_counts_close_to_the_counted_truth() {
    uint32_t walk = 0, seated = 0;
    replayFixture(&walk, &seated);
    printf("    real walk: %lu counted by the detector vs %d counted by hand\n",
           (unsigned long)walk, WALK_FIXTURE_COUNTED);

    // A band, not an equality. This is ONE walk by one person in one pocket, and
    // pinning an exact number would make the test a record of that afternoon
    // rather than a statement about the detector.
    //
    // The band is deliberately loose on the low side because the fixture contains
    // four ~411 ms sampling stalls, where the 30 s pet tick dirtied the save and
    // the blocking SPIFFS write starved the step poll. About 2.8 steps are simply
    // not in the data. Tightening this band by lowering the mg floor was tried and
    // REVERTED: it compensates for missing samples by making the detector more
    // eager, which is masking a structural bug with a tuning constant.
    ASSERT_GE((int)walk, (int)(WALK_FIXTURE_COUNTED * 0.90));
    ASSERT_LE((int)walk, (int)(WALK_FIXTURE_COUNTED * 1.06));
}

static void test_real_walk_does_not_invent_steps_while_seated() {
    uint32_t walk = 0, seated = 0;
    replayFixture(&walk, &seated);
    printf("    seated after %d ms: %lu false positives\n",
           WALK_FIXTURE_WALK_END_MS, (unsigned long)seated);

    // The walker sat down at ~100 s and did not walk again. Every step committed
    // after that is invented. Six of them were, before STEP_CADENCE_MIN went from
    // 2 to 3: each false positive committed EXACTLY 2 steps, because two bumps
    // from shifting in a seat satisfied a cadence run of 2 and were paid at once.
    // Requiring three in cadence rejects a two-peak burst outright and costs a
    // real walk only one extra held-back opener.
    //
    // Pinned at 4 rather than 0 because 4 is what the shipping constants actually
    // achieve on this walk. Asserting 0 would be asserting an aspiration.
    ASSERT_LE((int)seated, 4);
}

// ── A second real counted walk ────────────────────────────────────────────
//
// One walk is a calibration. Two walks are a check on it, and this second one
// is why the check was worth having: the first walk's noise floor never rose
// above the mg clamp, so it could not decide STEP_THRESHOLD_NUM at all and
// replayed identically at every ratio in the grid. This walk is louder, the
// ratio decides every crossing, and at the old 1.25x it found 153 of 164.
//
// It also carries the pickup that the owner reported: the capture's own header
// records 155, two more than any real footfall in the file, committed in a
// single event 69 s after walking stopped when the device was picked up. That
// is the STEP_CADENCE_MIN=2 signature, from a board still running the firmware
// that predates the fix.
static void test_second_real_walk_counts_close_to_the_counted_truth() {
    uint32_t walk = 0, still = 0;
    replayFixture2(&walk, &still);
    printf("    real walk 2: %lu counted by the detector vs %d counted by hand\n",
           (unsigned long)walk, WALK2_FIXTURE_COUNTED);

    // Banded on BOTH sides, and the upper bound is the point of the test.
    //
    // Ten sampling stalls cost this capture 2.3 s inside the walking phase.
    // Measuring each hole against the local gait interval (600 ms, 1.67 Hz) says
    // 3-4 footfalls happened while the detector was being fed nothing, so about
    // 161 is the most any detector can honestly find in this file. A parameter
    // set that reports more than that is not more accurate, it is inventing
    // steps to cover samples it never saw - which is exactly how a 1.0x ratio
    // scores 163 here and why it was not taken.
    ASSERT_GE((int)walk, 155);
    ASSERT_LE((int)walk, 162);
}

static void test_second_real_walk_does_not_invent_steps_while_still() {
    uint32_t walk = 0, still = 0;
    replayFixture2(&walk, &still);
    printf("    still after %d ms: %lu false positives "
           "(the capturing firmware's own total was %d)\n",
           WALK2_FIXTURE_WALK_END_MS, (unsigned long)still,
           WALK2_FIXTURE_DEVICE_STEPS);

    // 0, and here that is measured rather than aspirational: the only thing
    // that happened in the 76 s after this walk ended was the device being
    // picked up, and picking a device up is not walking. The firmware that took
    // the capture scored it 2. This is the regression guard for that report.
    ASSERT_LE((int)still, 0);
}

// Every way an expedition can end must say something different, because the
// whole point of the field is telling those cases apart afterwards. A new
// RoamEnd value that falls through to the default would render as "ended" and
// quietly put us back where this started.
static void test_every_end_reason_has_its_own_words() {
    const uint8_t reasons[] = {ROAM_END_USER, ROAM_END_DURATION,
                               ROAM_END_BATTERY, ROAM_END_REFUSED};
    const char* fallback = roamEndReasonName(0xFF);
    for (unsigned i = 0; i < sizeof(reasons); i++) {
        const char* a = roamEndReasonName(reasons[i]);
        ASSERT_TRUE(a != nullptr && a[0] != '\0');
        ASSERT_TRUE(strcmp(a, fallback) != 0);
        for (unsigned j = i + 1; j < sizeof(reasons); j++) {
            ASSERT_TRUE(strcmp(a, roamEndReasonName(reasons[j])) != 0);
        }
        // The narrowest panel is 160x80: 26 columns at text size 1, shared with
        // a "MM:SS  " clock. Anything longer than this silently runs off it.
        ASSERT_LE((int)strlen(a), 13);
    }
}

