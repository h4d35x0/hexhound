#if HEXHOUND_PANEL_ROUND

// ── Round panels (240x240 and 480x480) ────────────────────────────────────
//
// A grid in a circle wastes the circle, so the round den arranges the slots as
// a RING around the pet: the pet is in the middle of its room and its
// belongings are on the walls and floor around it. It is the same idea as the
// rim gauges on the home screen, and it is the one layout where the round
// glass is an advantage.
//
// ── Why the ring is an ELLIPSE ────────────────────────────────────────────
//
// A true circle only works for a slot count whose positions happen to miss 12
// and 6 o'clock, where the title and the footer live. A circle of radius 64
// centred at y=119 is fine for 8 slots offset by half a step, and puts the
// third of three slots at y=183 - straight through the footer rule at 190.
// Tuning the start angle per count would be a table of magic numbers that the
// next slot count silently invalidates.
//
// Squashing the ring vertically removes the problem instead of dodging it: the
// EXTREMES are bounded, so every slot is inside the body band for every count,
// including counts nobody has picked yet. rx=68, ry=52 about (CX, 119) puts
// every icon box inside y 59..179 against a body of 49..190, and inside
// x 44..196 against a chord of at least 6..234 over that band.
//
// Those numbers are 240-relative, so every one of them goes through
// uiround::scaled() and the 480 panel gets the same ring as a fraction of its
// glass. Written as raw pixels they would have drawn a 240-sized ring in the
// middle of a 480 screen, which is the same bug the room had.
static constexpr int RING_CX = uiround::CX;
static constexpr int RING_CY = uiround::scaled(119);
static constexpr int RING_RX = uiround::scaled(68);
static constexpr int RING_RY = uiround::scaled(52);
static_assert(uiround::DIAM != 240 ||
                  (RING_CY == 119 && RING_RX == 68 && RING_RY == 52),
              "240 den ring geometry shifted");

// The pet sits inside the ring. 72 px puts its corners 51 px from the centre,
// against an inner icon edge at ry - ICON_PX/2 - 2 = 42 straight down and
// rx - 10 = 58 straight out; the diagonal slots clear it because they are the
// ones furthest from the pet's flat sides.
static constexpr int ROUND_PET_PX = uiround::scaled(72);
static_assert(uiround::DIAM != 240 || ROUND_PET_PX == 72,
              "240 den pet size shifted");

void UIDen::drawRound() {
    const uint8_t visible = visibleSlots();

    DenLayout L;
    L.roomTop = uiround::HEADER_DIV + 1;
    L.roomBot = uiround::FOOTER_DIV;

    // The pet is centred in the ring, so the horizon is placed around IT
    // rather than the other way round. Two thirds of the way down the pet puts
    // the horizon BEHIND it, so the pet stands on the floor in front of the
    // back wall instead of being glued flat against it - which is both better
    // perspective and the only way this panel gets a floor worth the name.
    L.petPx = ROUND_PET_PX;
    L.petX  = RING_CX - L.petPx / 2;
    L.petY  = RING_CY - L.petPx / 2;
    L.railY = L.petY + (L.petPx * 2) / 3;

    _tft->fillScreen(TFT_BLACK);
    drawRoom(*_tft, L);
    drawPet(*_tft, L);

    const PetState& st = PetCore::instance().state();
    const uint8_t placed = denPlacedCount(st, visible);
    uint8_t selSlot = 0;
    const bool onSlot = (selectedKind(&selSlot) == DEN_ROW_SLOT);

    const float step = 360.0f / (float)(visible > 0 ? visible : 1);
    for (uint8_t s = 0; s < visible; s++) {
        const float a = (-90.0f + step * (float)s) * (float)PI / 180.0f;
        const int x = RING_CX + (int)(RING_RX * cosf(a));
        const int y = RING_CY + (int)(RING_RY * sinf(a));
        // baseY, not centre: drawSlot() stands an object on a shelf, and a
        // ring of objects standing on little shelves reads as a room rather
        // than as a dial of floating icons.
        drawSlot(*_tft, x, y + ICON_PX / 2, denItemAt(st, s),
                 onSlot && selSlot == s, 0, DEN_COL_WALL);
    }

    uiround::header(*_tft, "DEN", COL_HEADER);

    // No separate slot counter on this panel. The footer already carries it
    // whenever the cursor is on BACK, and a text plate anywhere else on the
    // glass would stamp a rectangle into the tiled room (see drawSlot).
    char left[28];
    footerLeft(left, sizeof(left));
    char hintBuf[56];
    snprintf(hintBuf, sizeof(hintBuf), "%s  %s", left, actionHint());
    uiround::footer(*_tft, hintBuf, placed == 0 ? COL_DIM : COL_DIVIDER);
}

#endif  // HEXHOUND_PANEL_ROUND
