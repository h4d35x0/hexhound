#define COL_HEADER   0x07FF   // cyan
#define COL_DIVIDER  0x07FF   // cyan
#define COL_SEL      0x07FF   // cyan  - the cursor
#define COL_TEXT     0xFFFF   // white
#define COL_DIM      0xC618   // light grey - the empty note

// Icons and tiles are generated by two different scripts into two different
// headers. They are sized by the same panel-family rule, and a slot laid out
// for one size holding an icon of the other would sit off its shelf.
static_assert(UI_ITEM_ICON_PX == DEN_TILE_PX,
              "item icons and den tiles disagree on the panel family size; "
              "re-run scripts/gen_item_icons.py and scripts/gen_den_art.py");

// ── Room scale ────────────────────────────────────────────────────────────
//
// DEN_SCALE is how much bigger this panel's room is than the 240 round one. It
// is 1 on every rectangular panel and on the 240 round one, so every expression
// below reduces to exactly what it was before on those boards, which is the
// only proof that a shipping board did not quietly move.
//
// It sizes the room's GEOMETRY - hairlines, insets, bracket arms, label text -
// and no longer sizes its ART. The tiles and the item icons used to be one
// 16 px set enlarged here to fill the 480 glass; both are now baked per panel
// family at the size they are drawn (8, 16 or 32 px), so DEN_TILE_PX and
// UI_ITEM_ICON_PX are the source AND the destination size and nothing on this
// screen enlarges anything. Blowing the icons up was the expensive half: they
// are supersampled and LANCZOS-downscaled, so doubling them turned every graded
// edge pixel into a 2x2 block. The drawn sizes are unchanged, so no layout
// moved; only the pixels got sharper.
//
// It is a MACRO rather than a constexpr because a place below has to emit
// DIFFERENT CODE, not just different numbers, and only the preprocessor can
// drop the branch it does not take. Leaving that decision to the optimiser was
// measured, and it was not free: a run-time branch on a compile-time-equal pair
// of sizes, plus a loop that runs once, cost the 240 board 80 bytes.
#if HEXHOUND_PANEL_ROUND
#define DEN_SCALE (SCREEN_W / 240)
static_assert(DEN_SCALE == uiround::TEXT_SCALE,
              "den art scale and round text scale must move together, or the "
              "room and its labels grow at different rates");
#else
#define DEN_SCALE 1
#endif

// What lands on glass. Equal to what the headers hold, by construction - see
// above - so there is no SRC/PX split left to get backwards.
static constexpr int TILE_PX = DEN_TILE_PX;
static constexpr int ICON_PX = UI_ITEM_ICON_PX;

// The room grows with DEN_SCALE but the art only grows when somebody bakes a
// set for the new size, and those two facts live in different files. This is
// what stops a future, larger round panel from laying out a room at 3x and then
// filling it with the 240 tiles at a third of the size it planned for: the
// build fails instead, naming the generators that have to be run.
static_assert(DEN_SCALE == 1 || TILE_PX == 16 * DEN_SCALE,
              "this panel's room is scaled up but its tiles and icons are not; "
              "add the size to SIZES in scripts/gen_den_art.py and "
              "scripts/gen_item_icons.py and re-run both");

// Hairlines and small offsets scale with the art, or the room grows while its
// details stay 1 px and the whole thing reads as a photograph of a smaller den.
static constexpr int DEN_HAIR = DEN_SCALE;

// Copy src into dst, clipped to maxPx pixels at charPx per glyph, ending in
// ".." when it did not fit. Same helper shape as ui_inventory.cpp and
// ui_quests.cpp, kept local for the same reason they keep theirs local: it is
// four lines, and hoisting it would mean editing two screens this workstream
// does not own.
static void fitText(char* dst, size_t dstSz, const char* src,
                    int maxPx, int charPx) {
    if (!dst || dstSz == 0) return;
    dst[0] = '\0';
    if (!src || charPx <= 0) return;

    int maxChars = maxPx / charPx;
    if (maxChars < 1) return;
    if ((size_t)maxChars > dstSz - 1) maxChars = (int)dstSz - 1;

    const int len = (int)strlen(src);
    if (len <= maxChars) {
        memcpy(dst, src, (size_t)len);
        dst[len] = '\0';
        return;
    }
    if (maxChars <= 2) {
        memcpy(dst, src, (size_t)maxChars);
        dst[maxChars] = '\0';
        return;
    }
    memcpy(dst, src, (size_t)(maxChars - 2));
    dst[maxChars - 2] = '.';
    dst[maxChars - 1] = '.';
    dst[maxChars]     = '\0';
}

// ── The room ──────────────────────────────────────────────────────────────

// Fill a rectangle with a seamless tile, clipped exactly to the rectangle.
//
// Phase-locked to ABSOLUTE screen coordinates rather than to the rectangle's
// own origin, so the wall band, the rail band and the floor band all land on
// the same lattice and the room reads as one surface instead of three strips.
// Runs of one colour go out as a single fillRect, the same trick drawSprite()
// uses: a tile row is mostly flat, so a 240 px row of wall costs about two
// calls per tile instead of sixteen.
//
// x0 and y0 are screen coordinates and never negative here, so the modulo does
// not need the sign fix-up.
//
// The lattice period is TILE_PX, which is both the drawn and the baked size, so
// a screen pixel maps to a source texel directly. This used to divide by
// DEN_SCALE to undo the enlargement; the 480 panel has its own 32 px tiles now,
// so there is no enlargement to undo.
static void tileBand(TFT_eSPI& t, int x0, int y0, int w, int h,
                     const uint16_t* tile) {
    if (w <= 0 || h <= 0) return;
    for (int y = 0; y < h; y++) {
        const uint16_t* row = &tile[((y0 + y) % TILE_PX) * TILE_PX];
        int x = 0;
        while (x < w) {
            const uint16_t c = pgm_read_word(&row[(x0 + x) % TILE_PX]);
            int run = 1;
            while (x + run < w &&
                   pgm_read_word(&row[(x0 + x + run) % TILE_PX]) == c) {
                run++;
            }
            t.fillRect(x0 + x, y0 + y, run, 1, c);
            x += run;
        }
    }
}

// Where everything in the room goes. Computed per draw rather than stored:
// it is a dozen integers derived from compile-time constants and the tier, and
// caching it would be a second copy of the layout to keep in step.
struct DenLayout {
    int roomTop  = 0;   // first row of the room
    int roomBot  = 0;   // one past the last row of the room
    int railY    = 0;   // top of the horizon band; the band is TILE_PX tall
    int petX     = 0;
    int petY     = 0;
    int petPx    = 0;   // drawn size; <= HD_HOME_PX, resized when the room is short
    uint8_t cols = 1;
    uint8_t rows = 1;
    int cellW    = 0;
    int gridX    = 0;   // left edge of the slot grid
    int rowBase[2] = { 0, 0 };   // the shelf / floor line each row stands on
};

// The horizon sits a little above the middle of the room, so the floor - where
// most of the objects stand - gets the deeper half.
static int railFor(int roomTop, int roomH) {
    return roomTop + (roomH * 45) / 100;
}

// The pet stands with its feet in the middle of the horizon band, and is
// resized down if the wall above the horizon is shorter than the HD art. Every
// panel therefore gets the largest pet its room can hold rather than a clipped
// one, and the resize is free on the panels where it does not happen.
static void placePet(DenLayout& L, int maxPx) {
    int px = (HD_HOME_PX < maxPx) ? HD_HOME_PX : maxPx;
    const int headroom = L.railY + TILE_PX / 2 - L.roomTop;
    if (px > headroom) px = headroom;
    if (px < 8) px = 8;
    L.petPx = px;
    L.petY  = L.railY + TILE_PX / 2 - px;
}

static void drawRoom(TFT_eSPI& t, const DenLayout& L) {
    tileBand(t, 0, L.roomTop, SCREEN_W, L.railY - L.roomTop, den_tile_wall);
    tileBand(t, 0, L.railY, SCREEN_W, TILE_PX, den_tile_rail);
    tileBand(t, 0, L.railY + TILE_PX, SCREEN_W,
             L.roomBot - L.railY - TILE_PX, den_tile_floor);
}

static void drawPet(TFT_eSPI& t, const DenLayout& L) {
    const PetStage stage = PetCore::instance().state().stage;

    // A grounding shadow first, so the pet is standing on the floor rather
    // than floating in front of a picture of one. Three shrinking bands is
    // enough to read as contact at 24 px and still not muddy at 72 px.
    const int cx = L.petX + L.petPx / 2;
    const int fy = L.petY + L.petPx;
    for (int i = 0; i < 3; i++) {
        const int hw = L.petPx / 3 - i * (L.petPx / 10) - 1;
        if (hw > 0) {
            t.fillRect(cx - hw, fy - 2 * DEN_HAIR + i * DEN_HAIR,
                       hw * 2, DEN_HAIR, DEN_COL_SHADOW);
        }
    }

    const uint16_t* art = getStageHomeHD(stage);
    if (L.petPx == HD_HOME_PX) {
        drawHDArt(t, art, L.petX, L.petY, HD_HOME_SRC_PX, HD_HOME_PX);
    } else {
        drawSpriteResized(t, art, HD_HOME_SRC_PX, HD_HOME_SRC_PX,
                          L.petX, L.petY, L.petPx, L.petPx);
    }
    // Whatever it is wearing comes with it into its own room. L.petPx, not
    // HD_HOME_PX: the den resizes the pet down when the room is short, and the
    // overlay is placed in thousandths of the size actually drawn.
    drawWornOn(t, stage, L.petX, L.petY, L.petPx);
}

// One placement slot, centred on cx and standing on baseY.
//
// The corner brackets are the affordance: they say "an object goes here" when
// the slot is empty, and they become the cursor when it is selected. That is
// why an EMPTY den is a room and not a blank wall - every slot the board shows
// is visibly a place, whether or not anything is in it.
static void drawSlot(TFT_eSPI& t, int cx, int baseY, uint8_t itemId,
                     bool selected, int labelW, uint16_t plate) {
    const int x0 = cx - ICON_PX / 2;
    const int y0 = baseY - ICON_PX;
    const bool empty = (itemId == DEN_SLOT_EMPTY);

    // The shelf the object stands on. Lit when selected so the cursor reads
    // even on a slot whose item already fills its brackets.
    const int over = 3 * DEN_SCALE;
    t.drawFastHLine(x0 - over, baseY, ICON_PX + over * 2,
                    selected ? COL_SEL : DEN_COL_RAIL);
#if DEN_SCALE > 1
    // The shelf is part of the art, not a rule, so it thickens with the room
    // instead of staying a hairline under a doubled icon.
    for (int i = 1; i < DEN_SCALE; i++) {
        t.drawFastHLine(x0 - over, baseY + i, ICON_PX + over * 2,
                        selected ? COL_SEL : DEN_COL_RAIL);
    }
#endif

    if (!empty) {
        // A plain blit on every panel: the icon is baked at ICON_PX for this
        // panel family, so there is no enlargement left to do. The 480 room
        // used to reach drawSpriteResized() here and stand 16 px art on a 32 px
        // shelf, which is what made the furniture look like a screenshot of a
        // smaller den.
        if (const uint16_t* icon = itemIconFor(itemId)) {
            drawSprite(t, icon, x0, y0, ICON_PX, ICON_PX);
        }
    }

    if (empty || selected) {
        const uint16_t c = selected ? COL_SEL : DEN_COL_RIVET;
        const int inset = 2 * DEN_SCALE;
        const int bx0 = x0 - inset, by0 = y0 - inset;
        const int bx1 = x0 + ICON_PX + inset - 1, by1 = y0 + ICON_PX + inset - 1;
        const int len = ((ICON_PX >= 16) ? 5 : 3) * DEN_SCALE;
        t.drawFastHLine(bx0, by0, len, c);
        t.drawFastVLine(bx0, by0, len, c);
        t.drawFastHLine(bx1 - len + 1, by0, len, c);
        t.drawFastVLine(bx1, by0, len, c);
        t.drawFastHLine(bx0, by1, len, c);
        t.drawFastVLine(bx0, by1 - len + 1, len, c);
        t.drawFastHLine(bx1 - len + 1, by1, len, c);
        t.drawFastVLine(bx1, by1 - len + 1, len, c);
    }

    // A name under the object, where the panel is wide enough for one. The
    // 160x80 passes labelW = 0: at 6 px per glyph a 41 px cell holds six
    // characters, and "FARAD.." under a lamp is noise, so that panel names the
    // selected slot in the footer instead.
    //
    // `plate` is the room colour BEHIND this row. Neither TFT_eSPI wrapper in
    // this firmware has a transparent-text path (setTextColor(fg) fills with
    // black), so a label drawn the obvious way would stamp a black rectangle
    // into the middle of the floor. Painting it in the surface's own base
    // colour is what makes the label sit ON the room instead of punching a
    // hole in it.
    if (labelW <= 0 || empty) return;
    const char* name = Inventory::instance().nameFor(itemId);
    char buf[20];
    fitText(buf, sizeof(buf), name, labelW, 6 * DEN_SCALE);
    if (!buf[0]) return;
    t.setTextSize(DEN_SCALE);
    t.setTextColor(selected ? COL_SEL : COL_TEXT, plate);
    t.setCursor(cx - (int)strlen(buf) * 3 * DEN_SCALE, baseY + 3 * DEN_SCALE);
    t.print(buf);
}

